#!/usr/bin/env bash
# Shared myos std/sysroot paths and version stamp for cache invalidation.
set -euo pipefail

MYOS_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
export MYOS_ROOT

myos_read_toolchain_channel() {
  local file="$MYOS_ROOT/rust-toolchain.toml"
  if [[ ! -f "$file" ]]; then
    echo "nightly-2026-07-26"
    return
  fi
  sed -n 's/^channel = "\(.*\)"/\1/p' "$file" | head -1
}

export MYOS_NIGHTLY="${MYOS_NIGHTLY:-$(myos_read_toolchain_channel)}"
export MYOS_SYSROOT="${MYOS_SYSROOT:-$MYOS_ROOT/target/myos-sysroot}"
export MYOS_SYSROOT_VERSION="$MYOS_SYSROOT/.myos-sysroot-version"
export MYOS_SYSROOT_MANIFEST="$MYOS_SYSROOT/myos-manifest.toml"

MYOS_USER_TRIPLES=(
  x86_64-unknown-myos
  aarch64-unknown-myos
  riscv64-unknown-myos
)
# Each arch once more on mlibc (`target_env = "mlibc"`: the C library's
# startup, heap, threads and keys under std, for a program with C or C++
# in it; docs/userspace.md "Rust userspace").
MYOS_MLIBC_TRIPLES=(
  x86_64-unknown-myos-mlibc
  aarch64-unknown-myos-mlibc
  riscv64-unknown-myos-mlibc
)
# The targets std is prebuilt for.
MYOS_SYSROOT_TRIPLES=("${MYOS_USER_TRIPLES[@]}" "${MYOS_MLIBC_TRIPLES[@]}")

myos_sysroot_version_hash() {
  # Content + stable relative paths (checkout-independent). xargs -r avoids
  # sha256sum reading stdin when find matches nothing.
  local h
  h="$(
    (
      cd "$MYOS_ROOT"
      {
        echo "toolchain=$MYOS_NIGHTLY"
        sha256sum "toolchain/std/patches/wire-myos.py"
        # Sources only; prune any nested cargo target/ dirs if present.
        # Nor the Cargo.lock cargo writes beside the vehicle's manifest
        # when std is built: the hash must be the same before and after.
        find toolchain/std/pal toolchain/std/sys toolchain/std/os toolchain/std/vehicle targets \
          \( -name target -o -path '*/target/*' -o -name Cargo.lock \) -prune -o \
          -type f -print0 2>/dev/null \
          | sort -z | xargs -0 -r sha256sum
      } | sha256sum | awk '{print $1}'
    )
  )"
  printf '%s' "$h"
}

myos_sysroot_is_current() {
  local triple
  [[ -f "$MYOS_SYSROOT_VERSION" ]] \
    && [[ -f "$MYOS_SYSROOT_MANIFEST" ]] \
    && [[ "$(cat "$MYOS_SYSROOT_VERSION")" == "$(myos_sysroot_version_hash)" ]] \
    || return 1
  for triple in "${MYOS_SYSROOT_TRIPLES[@]}"; do
    [[ -d "$MYOS_SYSROOT/lib/rustlib/$triple/lib" ]] || return 1
  done
}

myos_install_target_spec() {
  local triple="$1"
  cp "$MYOS_ROOT/targets/${triple}.json" \
    "$MYOS_SYSROOT/lib/rustlib/${triple}.json"
}

myos_install_std_rlibs() {
  local triple="$1"
  local deps_dir="$2"
  local dest="$MYOS_SYSROOT/lib/rustlib/${triple}/lib"
  mkdir -p "$dest"
  # Replace, not add to: a rebuilt std whose crate hash changed (a new
  # dependency) would otherwise sit beside the old one, and rustc refuses
  # to pick ("multiple candidates for rlib dependency std"); so would a
  # stale one left in the build's deps.
  rm -f "$dest"/*.rlib "$dest"/*.rmeta
  shopt -s nullglob
  local artifacts=() f
  for f in "$deps_dir"/*.rlib "$deps_dir"/*.rmeta; do
    # Not the library std was built on (the mlibc targets' vehicle).
    [[ "$(basename "$f")" == libmyos_sysroot_vehicle-* ]] || artifacts+=("$f")
  done
  shopt -u nullglob
  if ((${#artifacts[@]} == 0)); then
    echo "error: no std rlibs in $deps_dir" >&2
    exit 1
  fi
  cp -a "${artifacts[@]+"${artifacts[@]}"}" "$dest/"
  myos_install_target_spec "$triple"
}

myos_write_sysroot_manifest() {
  local version="$1"
  cat >"$MYOS_SYSROOT_MANIFEST" <<EOF
# myos prebuilt sysroot — generated by toolchain/std/build-sysroot.sh
channel = "$MYOS_NIGHTLY"
version = "$version"
triples = [$(printf '"%s", ' "${MYOS_SYSROOT_TRIPLES[@]}" | sed 's/, $//')]
repository = "https://github.com/davide-matasci/myos"
pal_hash = "$version"
EOF
}

myos_export_toolchain_env() {
  export RUSTC_BOOTSTRAP=1
  export MYOS_SYSROOT
  export RUSTC="$MYOS_ROOT/scripts/myos-rustc.sh"
}

myos_cargo_build_std() {
  local triple="$1"
  local profile="${2:-release}"
  local target_json="$MYOS_ROOT/targets/${triple}.json"
  local target_dir="$MYOS_ROOT/target/sysroot-build-${triple}"
  local manifest="$MYOS_ROOT/user/std/hello/Cargo.toml"
  # An mlibc target's program links libc.a: std is built on a library.
  [[ "$triple" == *-mlibc ]] && manifest="$MYOS_ROOT/toolchain/std/vehicle/Cargo.toml"
  local -a profile_args=()
  if [[ "$profile" == release ]]; then
    profile_args=(--release)
  fi

  myos_export_toolchain_env
  # Only this build's rlibs in deps: they are what gets installed.
  rm -rf "$target_dir/${triple}"
  # The mlibc targets unwind (LLVM's libunwind, toolchain/libcxx): the
  # unwinding panic runtime, and not the aborting one, which cargo builds
  # with the target's strategy and rustc then refuses ("does not have
  # the panic strategy `abort`").
  local crates=std,panic_abort features=compiler-builtins-mem
  if [[ "$triple" == *-mlibc ]]; then
    crates=std,panic_unwind
    features=compiler-builtins-mem,panic-unwind
  fi
  cargo "+$MYOS_NIGHTLY" build \
    -Z build-std="$crates" \
    -Z build-std-features="$features" \
    -Z unstable-options \
    -Z json-target-spec \
    --target "$target_json" \
    --target-dir "$target_dir" \
    "${profile_args[@]+"${profile_args[@]}"}" \
    --manifest-path "$manifest"

  myos_install_std_rlibs "$triple" "$target_dir/${triple}/${profile}/deps"
}

# myos_cargo_target_dir TRIPLE DIR: start DIR, a cargo target dir for TRIPLE,
# over when what it builds against changed. Cargo fingerprints the sources
# and flags it builds with, not the std sysroot, newlib (behind the libc
# crate) or the target spec outside them, so a target dir left by a build
# against other ones (an older local build, or the one CI's cache restores
# into target/) holds binaries it calls fresh and copies out again, old std
# and all, or rlibs rustc refuses next to the new std ("can't find crate",
# "found possibly newer version of crate `core`").
myos_cargo_target_dir() {
  local triple="$1" dir="$2" stamp
  stamp="$(cat "$MYOS_SYSROOT_VERSION" 2>/dev/null) $(cat "$MYOS_ROOT/target/.myos-newlib-version" 2>/dev/null) $MYOS_NIGHTLY $(sha256sum <"$MYOS_ROOT/targets/$triple.json" | cut -d' ' -f1)"
  if [[ "$(cat "$dir/.myos-toolchain" 2>/dev/null)" != "$stamp" ]]; then
    rm -rf "$dir"
    mkdir -p "$dir"
    printf '%s\n' "$stamp" >"$dir/.myos-toolchain"
  fi
}

myos_cargo_build_app() {
  local triple="$1"
  local profile="${2:-release}"
  local target_dir="$3"
  local manifest="$4"
  local bin="$5"
  local target_json="$MYOS_ROOT/targets/${triple}.json"
  local -a profile_args=()
  if [[ "$profile" == release ]]; then
    profile_args=(--release)
  fi

  myos_export_toolchain_env
  myos_cargo_target_dir "$triple" "$target_dir"
  cargo "+$MYOS_NIGHTLY" build \
    -Z unstable-options \
    -Z json-target-spec \
    --target "$target_json" \
    --target-dir "$target_dir" \
    "${profile_args[@]+"${profile_args[@]}"}" \
    --manifest-path "$manifest" \
    --bin "$bin"
}

MYOS_STD_HELLO_VERSION="$MYOS_ROOT/target/.myos-std-hello-version"

myos_std_hello_version_hash() {
  local h
  h="$(
    (
      cd "$MYOS_ROOT"
      {
        myos_sysroot_version_hash
        sha256sum "user/std/build.sh"
        # Sources only: Cargo.toml + *.rs. Ignore cargo outputs under
        # examples (target/, Cargo.lock, *.rlib, etc.) so the stamp is
        # stable across user/std/build.sh within one CI job.
        find user/std \
          \( -name target -o -path '*/target/*' \) -prune -o \
          -type f \( -name 'Cargo.toml' -o -name '*.rs' \) -print0 2>/dev/null \
          | sort -z | xargs -0 -r sha256sum
      } | sha256sum | awk '{print $1}'
    )
  )"
  printf '%s' "$h"
}

myos_std_hello_is_current() {
  local triple name
  [[ -f "$MYOS_STD_HELLO_VERSION" ]] \
    && [[ "$(cat "$MYOS_STD_HELLO_VERSION")" == "$(myos_std_hello_version_hash)" ]] \
    || return 1
  for triple in "${MYOS_USER_TRIPLES[@]+"${MYOS_USER_TRIPLES[@]}"}"; do
    for name in hello cat echo bigalloc sleep fs thread alloc; do
      [[ -f "$MYOS_ROOT/target/std-${name}-${triple}" ]] || return 1
    done
  done
}
