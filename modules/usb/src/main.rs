//! The USB core (`docs/usb.md`): the bus the class driver modules
//! (`usb_hub`, `usb_storage`, `usb_hid`) drive devices through, published as
//! the service [`USB_SERVICE`] (a [`UsbHostOps`] table), on the host
//! controllers their modules (`xhci`, `dwc2`) register here (the service
//! [`USB_CORE_SERVICE`], a [`UsbCoreOps`] table; each controller comes with
//! the [`UsbHcdOps`] its driver does the hardware's part through).
//! Enumeration, hot-plug and the drivers' hooks run on one kernel thread
//! (`thread_main`); a controller's interrupt handler only tells the thread
//! to look (`port_change`, `wake`). The hubs below the root ports are a
//! class driver's business (`usb_hub`) that hands children back through
//! `hub_attach`.

#![no_std]
#![no_main]
#![deny(unsafe_op_in_unsafe_fn)]

mod bus;
mod sync;

use core::ffi::c_void;
use core::sync::atomic::{AtomicBool, AtomicU32, AtomicU64, Ordering};

use myos_abi::{
    ABI_VERSION, ApiCell, KernelApi, USB_CORE_SERVICE, USB_CORE_VERSION, USB_EGONE, USB_HCD_VERSION,
    USB_HOST_VERSION, USB_LABEL_MAX, USB_SERVICE, UsbCompletion, UsbCoreOps, UsbDeviceInfo, UsbDriverOps,
    UsbHcdOps, UsbHostOps, UsbPortStatus, status_fail, status_ok,
};

/// Controllers the core drives.
pub const MAX_CTRL: usize = 4;

/// A registered host controller: its driver's table and the handle the
/// driver knows it by.
pub struct Controller {
    pub ops: &'static UsbHcdOps,
    pub ctx: usize,
    pub index: u8,
    pub ports: u8,
    /// Root ports whose status changed (bit = port index), for the thread.
    pub port_change: AtomicU64,
}

static API: ApiCell = ApiCell::new();
/// The controllers, each set once by `controller_register` and read by
/// every context after (`controller`).
static CONTROLLERS: [sync::Once<Controller>; MAX_CTRL] = [const { sync::Once::new() }; MAX_CTRL];
/// The USB thread sleeps on this key; the controllers' handlers,
/// `driver_register` and the hub calls wake it.
pub static THREAD_KEY: AtomicU32 = AtomicU32::new(0);
/// A driver registered: offer the unclaimed interfaces again.
static REOFFER: AtomicBool = AtomicBool::new(false);
/// A controller reported a completion: look for queued transfers done.
static ASYNC_DONE: AtomicBool = AtomicBool::new(false);
static PROC_DIRTY: AtomicBool = AtomicBool::new(false);

pub fn api() -> &'static KernelApi {
    API.get()
}

pub fn controller(i: u8) -> Option<&'static Controller> {
    CONTROLLERS.get(usize::from(i))?.get()
}

/// Sleep the calling task `ms` milliseconds.
pub fn sleep_ms(ms: u64) {
    let until = api().monotonic_ns() + ms * 1_000_000;
    api().task_sleep_until(until);
}

fn wake_thread() {
    api().wake(THREAD_KEY.as_ptr() as usize);
}

/// `/proc/usb` is regenerated by the thread after a change.
pub fn proc_update() {
    PROC_DIRTY.store(true, Ordering::Release);
    wake_thread();
}

fn proc_write() {
    let mut buf = [0u8; 4096];
    let n = bus::proc_text(&mut buf);
    api().proc_register("usb", &buf[..n]);
}

/// A small text writer for the proc node and the log.
pub struct Writer<'a> {
    pub buf: &'a mut [u8],
    pub len: usize,
}

impl Writer<'_> {
    pub fn bytes(&mut self, b: &[u8]) {
        let n = b.len().min(self.buf.len() - self.len);
        self.buf[self.len..self.len + n].copy_from_slice(&b[..n]);
        self.len += n;
    }
    pub fn str(&mut self, s: &str) {
        self.bytes(s.as_bytes());
    }
    pub fn dec(&mut self, mut v: u32) {
        let mut t = [0u8; 10];
        let mut n = 0;
        loop {
            t[n] = b'0' + (v % 10) as u8;
            n += 1;
            v /= 10;
            if v == 0 {
                break;
            }
        }
        t[..n].reverse();
        self.bytes(&t[..n]);
    }
    fn hexn(&mut self, v: u64, digits: usize) {
        let mut t = [0u8; 16];
        for i in 0..digits {
            let d = ((v >> (4 * (digits - 1 - i))) & 0xF) as u8;
            t[i] = if d < 10 { b'0' + d } else { b'a' + d - 10 };
        }
        self.bytes(&t[..digits]);
    }
    pub fn hex(&mut self, v: u32) {
        self.str("0x");
        self.hexn(u64::from(v), 3);
    }
    pub fn hex4(&mut self, v: u16) {
        self.hexn(u64::from(v), 4);
    }
    pub fn hex2(&mut self, v: u8) {
        self.hexn(u64::from(v), 2);
    }
}

// ---- The class drivers' table -------------------------------------------------

static HOST_OPS: UsbHostOps = UsbHostOps {
    version: USB_HOST_VERSION,
    driver_register,
    control,
    bulk,
    interrupt_start,
    clear_halt,
    hub_configure,
    hub_attach,
    hub_detach,
    device_info,
    interface_label,
};

unsafe extern "C" fn driver_register(ops: *const UsbDriverOps) -> i32 {
    if ops.is_null() {
        return -1;
    }
    let mut drivers = bus::DRIVERS.lock();
    let Some(slot) = drivers.iter().position(|d| d.is_none()) else {
        return -1;
    };
    // SAFETY: a driver's table lives as long as its module, which stays
    // loaded while it is registered here (`docs/usb.md`).
    drivers[slot] = Some(unsafe { &*ops });
    drop(drivers);
    REOFFER.store(true, Ordering::Release);
    wake_thread();
    0
}

/// `bus::with_device` for a hook: the device's lock held for `f`, and
/// `USB_EGONE` when the device is not there.
fn on_device(dev: u32, f: impl FnOnce(&Controller, &bus::Slot, &mut bus::Device) -> i32) -> i32 {
    bus::with_device(dev, f).unwrap_or_else(|e| e)
}

unsafe extern "C" fn control(dev: u32, request_type: u8, request: u8, value: u16, index: u16, data: *mut u8, len: u16) -> i32 {
    if len != 0 && data.is_null() {
        return -1;
    }
    on_device(dev, |c, _, d| bus::control(c, d, request_type, request, value, index, data, len))
}

unsafe extern "C" fn bulk(dev: u32, endpoint: u8, data: *mut u8, len: usize, timeout_ms: u32) -> i32 {
    if data.is_null() && len != 0 {
        return -1;
    }
    on_device(dev, |c, _, d| unsafe { (c.ops.bulk)(c.ctx, d.hdev, endpoint, data, len, timeout_ms) })
}

unsafe extern "C" fn interrupt_start(dev: u32, endpoint: u8, data: *mut u8, len: usize, done: UsbCompletion, ctx: *mut c_void) -> i32 {
    if data.is_null() || len == 0 {
        return -1;
    }
    on_device(dev, |c, _, d| bus::interrupt_start(c, d, endpoint, data, len, done, ctx))
}

unsafe extern "C" fn clear_halt(dev: u32, endpoint: u8) -> i32 {
    on_device(dev, |c, _, d| bus::clear_halt(c, d, endpoint))
}

unsafe extern "C" fn hub_configure(dev: u32, ports: u8, tt_think: u8, multi_tt: u8) -> i32 {
    on_device(dev, |c, _, d| {
        d.hub_ports = ports;
        unsafe { (c.ops.device_hub)(c.ctx, d.hdev, ports, tt_think, multi_tt) }
    })
}

/// The controller of the hub `dev`, if the hub is there.
fn hub_controller(dev: u32) -> Option<&'static Controller> {
    let index = bus::with_device(dev, |c, _, _| c.index).ok()?;
    controller(index)
}

unsafe extern "C" fn hub_attach(dev: u32, port: u8, speed: u8) -> i32 {
    let Some(c) = hub_controller(dev) else {
        return USB_EGONE;
    };
    if let Some(child) = bus::find(c.index, dev, port) {
        bus::detach_id(c, child);
    }
    match bus::attach(c, Some((dev, port)), 0, speed) {
        Ok(id) => id as i32,
        Err(e) => {
            enumeration_failed(c, e);
            e
        }
    }
}

unsafe extern "C" fn hub_detach(dev: u32, port: u8) {
    let Some(c) = hub_controller(dev) else {
        return;
    };
    if let Some(child) = bus::find(c.index, dev, port) {
        bus::detach_id(c, child);
    }
}

unsafe extern "C" fn device_info(dev: u32, info: *mut UsbDeviceInfo) -> i32 {
    if info.is_null() {
        return -1;
    }
    on_device(dev, |_, _, d| {
        unsafe {
            *info = d.info;
        }
        0
    })
}

unsafe extern "C" fn interface_label(dev: u32, intf: u8, label: *const u8, len: usize) -> i32 {
    let len = len.min(USB_LABEL_MAX);
    if len != 0 && label.is_null() {
        return -1;
    }
    let rc = on_device(dev, |_, _, d| {
        let Some(i) = d.interfaces.iter_mut().flatten().find(|i| i.info.number == intf) else {
            return -1;
        };
        if len != 0 {
            i.label[..len].copy_from_slice(unsafe { core::slice::from_raw_parts(label, len) });
        }
        i.label_len = len as u8;
        0
    });
    if rc == 0 {
        proc_update();
    }
    rc
}

// ---- The host controller drivers' table ---------------------------------------

static CORE_OPS: UsbCoreOps = UsbCoreOps { version: USB_CORE_VERSION, controller_register, port_change, wake };

unsafe extern "C" fn controller_register(ops: *const UsbHcdOps, ctx: usize) -> i32 {
    if ops.is_null() {
        return -1;
    }
    // SAFETY: a driver's table lives as long as its module, which stays
    // loaded while it holds our service.
    let ops: &'static UsbHcdOps = unsafe { &*ops };
    if ops.version != USB_HCD_VERSION {
        return -2;
    }
    let Some(index) = CONTROLLERS.iter().position(|c| c.get().is_none()) else {
        return -3;
    };
    let ports = unsafe { (ops.ports)(ctx) };
    let c = Controller { ops, ctx, index: index as u8, ports, port_change: AtomicU64::new(0) };
    // Every port looked at once: the devices plugged in before.
    c.port_change.store(u64::MAX >> (64 - usize::from(ports).clamp(1, 64)), Ordering::Relaxed);
    if !CONTROLLERS[index].set(c) {
        return -3;
    }
    proc_update();
    index as i32
}

unsafe extern "C" fn port_change(index: u32, port: u8) {
    let Some(c) = u8::try_from(index).ok().and_then(controller) else {
        return;
    };
    c.port_change.fetch_or(1 << port.min(63), Ordering::Release);
    wake_thread();
}

unsafe extern "C" fn wake(index: u32) {
    if u8::try_from(index).ok().and_then(controller).is_none() {
        return;
    }
    ASYNC_DONE.store(true, Ordering::Release);
    wake_thread();
}

// ---- The thread --------------------------------------------------------------

/// Root port `port` (0-based) of `c`: its state, with its change bits
/// acknowledged.
fn port_status(c: &Controller, port: u8) -> UsbPortStatus {
    let mut s = UsbPortStatus::default();
    unsafe { (c.ops.port_status)(c.ctx, port, &mut s) };
    s
}

/// A root port's status changed (or the initial scan): a new device is
/// reset and enumerated, a vanished one detached.
fn root_port(c: &Controller, port: u8) {
    let s = port_status(c, port);
    let present = bus::find(c.index, 0, port + 1);
    if s.connected != 0 && present.is_none() {
        // Debounce, then reset (the driver leaves a USB 3 link that
        // trained itself alone).
        sleep_ms(100);
        if port_status(c, port).connected == 0 {
            return;
        }
        if unsafe { (c.ops.port_reset)(c.ctx, port) } != 0 {
            return;
        }
        let s = port_status(c, port);
        if s.connected == 0 || s.enabled == 0 {
            return;
        }
        if let Err(e) = bus::attach(c, None, port + 1, s.speed) {
            enumeration_failed(c, e);
        }
    } else if s.connected == 0 {
        if let Some(id) = present {
            bus::detach_id(c, id);
        }
    }
}

/// `[ FAIL ] usb: <step> failed (<code>) <controller>`: the step of
/// `bus::enumerate`, the `USB_E*` or the driver's error, and what the
/// driver says of the controller.
pub fn enumeration_failed(c: &Controller, e: i32) {
    let mut buf = [0u8; 128];
    let mut w = Writer { buf: &mut buf, len: 0 };
    w.str("usb: ");
    w.str(*bus::STEP.lock());
    w.str(" failed (");
    if e < 0 {
        w.str("-");
    }
    w.dec(e.unsigned_abs());
    w.str(") ");
    let n = w.len;
    let m = unsafe { (c.ops.describe)(c.ctx, w.buf[n..].as_mut_ptr(), w.buf.len() - n) };
    let n = n + m.min(w.buf.len() - n);
    status_fail(api(), core::str::from_utf8(&buf[..n]).unwrap_or("usb"));
}

unsafe extern "C" fn thread_main(_ctx: *mut c_void) {
    loop {
        let seq = api().wait_seq();
        let mut worked = false;
        let mut polled = false;
        for i in 0..MAX_CTRL as u8 {
            let Some(c) = controller(i) else {
                continue;
            };
            polled |= unsafe { (c.ops.poll)(c.ctx) } != 0;
            let changed = c.port_change.swap(0, Ordering::AcqRel);
            if changed != 0 {
                worked = true;
                for port in 0..c.ports.min(64) {
                    if changed & (1 << port) != 0 {
                        root_port(c, port);
                    }
                }
            }
        }
        if ASYNC_DONE.swap(false, Ordering::AcqRel) {
            worked = true;
            bus::run_async_completions();
        }
        if REOFFER.swap(false, Ordering::AcqRel) {
            worked = true;
            bus::offer_all();
        }
        if PROC_DIRTY.swap(false, Ordering::AcqRel) {
            proc_write();
        }
        if worked {
            continue;
        }
        // A controller without an interrupt is looked at every 20 ms.
        let now = api().monotonic_ns();
        let deadline = if polled { now + 20_000_000 } else { now + 1_000_000_000 };
        api().block_until(THREAD_KEY.as_ptr() as usize, seq, deadline);
    }
}

#[inline(never)]
#[unsafe(no_mangle)]
pub unsafe extern "C" fn module_init(api_ptr: *const KernelApi) -> i32 {
    if api_ptr.is_null() {
        return -1;
    }
    let api: &'static KernelApi = unsafe { &*api_ptr };
    if api.abi_version != ABI_VERSION {
        return -2;
    }
    unsafe { API.set(api) };
    if api.service_register(USB_CORE_SERVICE, &CORE_OPS) != 0 {
        status_fail(api, "usb: usbcore service");
        return -3;
    }
    if api.service_register(USB_SERVICE, &HOST_OPS) != 0 {
        status_fail(api, "usb: usb service");
        return -3;
    }
    if api.thread_spawn("usb", thread_main, core::ptr::null_mut()) != 0 {
        status_fail(api, "usb: no thread");
        return -4;
    }
    proc_write();
    status_ok(api, "usb");
    0
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn module_exit() {}

// So `cargo build --bin usb` links. The kernel never jumps here.
#[unsafe(no_mangle)]
pub extern "C" fn _start() -> ! {
    loop {}
}

#[panic_handler]
fn panic(info: &core::panic::PanicInfo) -> ! {
    let api = api();
    let mut buf = [0u8; 96];
    let mut w = Writer { buf: &mut buf, len: 0 };
    w.str("usb: panic");
    if let Some(l) = info.location() {
        // The file's name, not a registry path.
        let file = l.file();
        let tail = file.rsplit('/').next().unwrap_or(file);
        w.str(" at ");
        w.str(tail);
        w.str(":");
        w.dec(l.line());
    }
    let n = w.len;
    status_fail(api, core::str::from_utf8(&buf[..n]).unwrap_or("usb: panic"));
    loop {
        api.task_yield();
    }
}
